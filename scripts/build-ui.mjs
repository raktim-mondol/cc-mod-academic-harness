#!/usr/bin/env node
// Copy the two browser-safe upstream modules the interface uses into hooks/generated/ (plan P5):
//   task-modes.js  the task catalogue and the effort tables that map a task to tool arguments
//   fold-core.js   the reply fold at five levels
// Both are pure ESM with no Node or React imports, so the hooks module can bundle them. The copy is byte for byte after a header
// and `// @ts-nocheck` (the source is JavaScript), and a test checks the copy against the snapshot, so drift fails loudly.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const COPIES = [['task-modes.js', 'task-modes.ts'], ['fold-core.js', 'fold-core.ts']]

export function header(commit, from) {
  return `// Generated by scripts/build-ui.mjs from upstream ${commit.slice(0, 7)} (${from}). Do not edit.\n// @ts-nocheck: the source is JavaScript, copied as it is.\n`
}

export function build({ upstream = join(root, 'upstream'), out = join(root, 'hooks', 'generated') } = {}) {
  const lock = JSON.parse(readFileSync(join(root, 'UPSTREAM.lock.json'), 'utf8'))
  mkdirSync(out, { recursive: true })
  const written = []
  for (const [from, to] of COPIES) {
    const text = readFileSync(join(upstream, from), 'utf8')
    if (/^\s*import\s/m.test(text)) throw new Error(`${from} imports something: it is no longer browser-safe, so it cannot be copied into the hooks module`)
    writeFileSync(join(out, to), header(lock.commit, from) + text)
    written.push(to)
  }
  return written
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`ui: copied ${build().join(', ')} into hooks/generated`)
}
