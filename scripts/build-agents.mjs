#!/usr/bin/env node
// Build agents/*.md: one Claude Code agent definition per Academic Harness specialist.
//
//   node scripts/build-agents.mjs
//
// The specialist names come from the `## Specialists` section of upstream/prompt.js (the four
// "Group: a, b, c." lines), so a specialist added or removed upstream shows up here. Each brief is
// the body of upstream/skills/<name>/SKILL.md after the line that tells DeepSeek Harness how to
// delegate it; that line is host-specific and is replaced by the agent mechanism itself.
//
// Reviewers and checkers get no Edit, Write or NotebookEdit: the guidance says specialists "do not
// silently edit unless asked". The agents that build or write things keep them (EDITORS below).
// Never edit agents/ by hand (ground rule 5).

import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { frontmatter } from './build-skills.mjs'
import { DROPPED_AGENTS } from '../server/src/fit.mjs'
import { adapt } from './adapt.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

export const EDITORS = new Set(['manuscript-editor', 'abstract-writer', 'protocol-writer', 'data-visualizer', 'paper-agent-builder'])
const READ_ONLY_DENY = 'Edit, Write, NotebookEdit'
// The sentence upstream puts in every brief to tell DeepSeek Harness how to delegate it.
const DELEGATION = /When DeepSeek Harness delegates this specialist[\s\S]*?together with the concrete task\.\s*/

/** The names in the "Group: a, b, c." lines of the Specialists section. */
export function specialistNames(promptText) {
  const section = String(promptText).split(/\n(?=## )/).find(p => p.startsWith('## Specialists'))
  if (!section) throw new Error('prompt.js has no "## Specialists" section')
  const names = []
  for (const line of section.split('\n')) {
    const m = line.match(/^(?:Code & computation|Literature & verification|Design|Writing): (.+)\.$/)
    if (m) names.push(...m[1].split(',').map(s => s.trim()).filter(Boolean))
  }
  if (names.length === 0) throw new Error('found no specialist names in the Specialists section')
  return names
}

/** @returns {string} the agent file text */
export function agentFile(name, skillText) {
  const fm = frontmatter(skillText)
  if (!fm?.description) throw new Error(`${name}: skill has no description`)
  const body = skillText.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '')
  if (!DELEGATION.test(body)) throw new Error(`${name}: the delegation line is not where this build expects it (upstream changed the brief format)`)
  const brief = adapt(`agent:${name}`, body.replace(DELEGATION, '').trim())
  const head = ['---', `name: ${name}`, `description: ${JSON.stringify(fm.description)}`]
  if (!EDITORS.has(name)) head.push(`disallowedTools: ${READ_ONLY_DENY}`)
  head.push('---')
  return [
    ...head,
    '',
    `<!-- Generated by scripts/build-agents.mjs from the upstream "${name}" skill. Do not edit. -->`,
    '',
    brief,
    '',
    '## Host notes',
    '',
    'You are running as a Claude Code subagent. Tool names in this brief are Academic Harness\'s own; if a tool it names is not in your tool list, say so rather than describing work you could not do. Report findings by severity, with file:line or the quoted claim.',
    '',
  ].join('\n')
}

export async function build({ upstream = join(root, 'upstream'), out = join(root, 'agents') } = {}) {
  const mod = await import(pathToFileURL(join(upstream, 'prompt.js')).href)
  const names = specialistNames(mod.ACADEMIC_HARNESS_PROMPT)
  rmSync(out, { recursive: true, force: true })
  mkdirSync(out, { recursive: true })
  for (const name of names) {
    if (DROPPED_AGENTS[name]) continue
    const text = readFileSync(join(upstream, 'skills', name, 'SKILL.md'), 'utf8')
    writeFileSync(join(out, `${name}.md`), agentFile(name, text))
  }
  const stale = [...EDITORS].filter(n => !names.includes(n))
  return { names, stale, files: readdirSync(out).length }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = await build()
  const readOnly = r.names.filter(n => !EDITORS.has(n)).length
  console.log(`agents: ${r.files} written (${readOnly} read-only, ${r.names.length - readOnly} with edit tools)`)
  if (r.stale.length) console.log(`  EDITORS names no longer upstream: ${r.stale.join(', ')}`)
}
